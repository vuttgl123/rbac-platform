SET LOCAL ROLE rbac_owner;

-- V12: per-service transactional outbox. Each service that publishes events owns an <schema>.outbox table in its
-- own schema (identity, authz), written in the same transaction as the change it describes and drained by a
-- relay (claim, publish, complete or reschedule). util.create_outbox builds the table, its policies and its
-- functions once per service, so both copies are identical by construction.
--
-- Writer side: the service role is INSERT-only. It cannot SELECT, UPDATE or DELETE, so it cannot use
-- INSERT ... RETURNING or ON CONFLICT (both need SELECT); the row id is generated by the database and the writer
-- never needs it back. RLS (FORCE) limits the insert to the current tenant.
--
-- Relay side: the relay is the same service role, but it works across all tenants, which RLS would hide, so
-- every relay operation is a SECURITY DEFINER function owned by rbac_owner (the owner_all policy lets it
-- through). outbox_claim is a lease: it bumps attempts and pushes next_attempt_at to now() + p_lease, stamping a
-- claim_token. A relay that crashes simply lets the lease expire and the row is claimed again; a slow relay that
-- comes back after its lease expired holds a stale token, so outbox_complete and outbox_reschedule (which match
-- on the token) do nothing for it. Concurrent relays are kept apart by FOR UPDATE SKIP LOCKED.
--
-- Operator side: rows the relay gave up on are 'dead'. rbac_admin lists them (outbox_dead) and puts them back
-- (outbox_requeue); the service role cannot.
--
-- tenant_id deliberately has NO foreign key to tenancy.tenants, for the same reason as audit.events (V8): the
-- table is a queue that must not block a tenant hard-delete nor pay RI cost per insert.

-- util.create_outbox: owner-only (EXECUTE revoked from PUBLIC, not a definer). Creates <p_schema>.outbox and its
-- five functions and grants them to p_role (relay operations) and rbac_admin (operator operations).
CREATE FUNCTION util.create_outbox(p_schema text, p_role regrole) RETURNS void
    LANGUAGE plpgsql
    SET search_path = pg_catalog, extensions
AS $$
BEGIN
    IF p_schema IS NULL OR p_role IS NULL
       OR NOT EXISTS (SELECT 1 FROM pg_namespace n WHERE n.nspname = p_schema AND n.nspowner = 'rbac_owner'::regrole)
    THEN
        RAISE EXCEPTION 'invalid_argument: schema % must exist and be owned by rbac_owner', p_schema
            USING ERRCODE = 'invalid_parameter_value';
    END IF;

    EXECUTE format($t$
        CREATE TABLE %1$I.outbox (
            tenant_id       uuid        NOT NULL,
            id              uuid        PRIMARY KEY DEFAULT util.uuid_v7(),
            aggregate_type  text        NOT NULL,
            aggregate_id    text        NOT NULL,
            event_type      text        NOT NULL,
            payload         jsonb       NOT NULL,
            headers         jsonb       NOT NULL DEFAULT '{}',
            created_at      timestamptz NOT NULL DEFAULT now(),
            status          text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'dead')),
            attempts        int         NOT NULL DEFAULT 0,
            next_attempt_at timestamptz NOT NULL DEFAULT now(),
            claim_token     uuid,
            last_error      text
        ) WITH (autovacuum_vacuum_scale_factor = 0.01, autovacuum_vacuum_threshold = 50)$t$, p_schema);

    EXECUTE format('CREATE INDEX outbox_pending_idx ON %I.outbox (next_attempt_at, id) WHERE status = ''pending''',
                   p_schema);

    EXECUTE format('ALTER TABLE %I.outbox ENABLE ROW LEVEL SECURITY', p_schema);
    EXECUTE format('ALTER TABLE %I.outbox FORCE ROW LEVEL SECURITY', p_schema);
    EXECUTE format(
        'CREATE POLICY tenant_isolation ON %I.outbox FOR INSERT TO %s '
        'WITH CHECK (tenant_id = (SELECT util.current_tenant_id()))', p_schema, p_role::text);
    EXECUTE format(
        'CREATE POLICY owner_all ON %I.outbox FOR ALL TO rbac_owner USING (true) WITH CHECK (true)', p_schema);
    EXECUTE format('GRANT INSERT ON %I.outbox TO %s', p_schema, p_role::text);

    -- outbox_claim: lease up to p_limit due rows.
    EXECUTE format($t$
        CREATE FUNCTION %1$I.outbox_claim(p_limit int, p_lease interval, p_token uuid) RETURNS SETOF %1$I.outbox
            LANGUAGE plpgsql SECURITY DEFINER
            SET search_path = pg_catalog, extensions
        AS $fn$
        BEGIN
            IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 1000 OR p_lease IS NULL OR p_lease <= interval '0'
               OR p_token IS NULL THEN
                RAISE EXCEPTION 'invalid_argument: p_limit must be 1..1000, p_lease positive and p_token set'
                    USING ERRCODE = 'invalid_parameter_value';
            END IF;
            RETURN QUERY
            WITH claimed AS (
                UPDATE %1$I.outbox o
                SET attempts = o.attempts + 1, next_attempt_at = now() + p_lease, claim_token = p_token
                WHERE o.id IN (SELECT q.id FROM %1$I.outbox q
                               WHERE q.status = 'pending' AND q.next_attempt_at <= now()
                               ORDER BY q.next_attempt_at, q.id
                               LIMIT p_limit
                               FOR UPDATE SKIP LOCKED)
                RETURNING o.*
            )
            SELECT * FROM claimed;
        END
        $fn$ $t$, p_schema);

    -- outbox_complete: delete delivered rows the caller still holds the lease on.
    EXECUTE format($t$
        CREATE FUNCTION %1$I.outbox_complete(p_token uuid, p_ids uuid[]) RETURNS int
            LANGUAGE plpgsql SECURITY DEFINER
            SET search_path = pg_catalog, extensions
        AS $fn$
        DECLARE
            v_count int;
        BEGIN
            DELETE FROM %1$I.outbox o
            WHERE o.id = ANY (p_ids) AND o.claim_token = p_token AND o.status = 'pending';
            GET DIAGNOSTICS v_count = ROW_COUNT;
            RETURN v_count;
        END
        $fn$ $t$, p_schema);

    -- outbox_reschedule: release a claimed row for a later retry, or bury it.
    EXECUTE format($t$
        CREATE FUNCTION %1$I.outbox_reschedule(p_token uuid, p_id uuid, p_error text, p_next_attempt_at timestamptz,
                                               p_dead boolean) RETURNS boolean
            LANGUAGE plpgsql SECURITY DEFINER
            SET search_path = pg_catalog, extensions
        AS $fn$
        DECLARE
            v_count int;
        BEGIN
            UPDATE %1$I.outbox o
            SET status = CASE WHEN p_dead THEN 'dead' ELSE 'pending' END,
                next_attempt_at = coalesce(p_next_attempt_at, now()),
                last_error = left(p_error, 2000),
                claim_token = NULL
            WHERE o.id = p_id AND o.claim_token = p_token AND o.status = 'pending';
            GET DIAGNOSTICS v_count = ROW_COUNT;
            RETURN v_count > 0;
        END
        $fn$ $t$, p_schema);

    -- outbox_dead: operator listing of buried rows, every tenant.
    EXECUTE format($t$
        CREATE FUNCTION %1$I.outbox_dead(p_limit int) RETURNS SETOF %1$I.outbox
            LANGUAGE plpgsql SECURITY DEFINER
            SET search_path = pg_catalog, extensions
        AS $fn$
        BEGIN
            IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 1000 THEN
                RAISE EXCEPTION 'invalid_argument: p_limit must be 1..1000'
                    USING ERRCODE = 'invalid_parameter_value';
            END IF;
            RETURN QUERY
            SELECT * FROM %1$I.outbox o WHERE o.status = 'dead' ORDER BY o.created_at, o.id LIMIT p_limit;
        END
        $fn$ $t$, p_schema);

    -- outbox_requeue: operator puts buried rows back in the queue with a fresh retry budget.
    EXECUTE format($t$
        CREATE FUNCTION %1$I.outbox_requeue(p_ids uuid[]) RETURNS int
            LANGUAGE plpgsql SECURITY DEFINER
            SET search_path = pg_catalog, extensions
        AS $fn$
        DECLARE
            v_count int;
        BEGIN
            UPDATE %1$I.outbox o
            SET status = 'pending', attempts = 0, next_attempt_at = now(), claim_token = NULL, last_error = NULL
            WHERE o.id = ANY (p_ids) AND o.status = 'dead';
            GET DIAGNOSTICS v_count = ROW_COUNT;
            RETURN v_count;
        END
        $fn$ $t$, p_schema);

    EXECUTE format('REVOKE EXECUTE ON FUNCTION %1$I.outbox_claim(int, interval, uuid), '
                   '%1$I.outbox_complete(uuid, uuid[]), '
                   '%1$I.outbox_reschedule(uuid, uuid, text, timestamptz, boolean), '
                   '%1$I.outbox_dead(int), %1$I.outbox_requeue(uuid[]) FROM PUBLIC', p_schema);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %1$I.outbox_claim(int, interval, uuid), '
                   '%1$I.outbox_complete(uuid, uuid[]), '
                   '%1$I.outbox_reschedule(uuid, uuid, text, timestamptz, boolean) TO %2$s', p_schema, p_role::text);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %1$I.outbox_dead(int), %1$I.outbox_requeue(uuid[]) TO rbac_admin',
                   p_schema);
END
$$;

REVOKE EXECUTE ON FUNCTION util.create_outbox(text, regrole) FROM PUBLIC;

SELECT util.create_outbox('identity', 'identity_app');
SELECT util.create_outbox('authz', 'authz_app');
